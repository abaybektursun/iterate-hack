"""Freeze the input of selfopen-01 (specs/SPEC_selfopen01.md): which stored T3 rows already self-open.

    aws s3 cp s3://pg-lineage-769063704696/results/rlneurons/r4/modal_t3-01/t3/T3.jsonl runs/selfopen01/T3.jsonl --profile iterate-ecr
    uv run python -m studies.theory.prep.selfopen01_t3 runs/selfopen01/T3.jsonl

Writes studies/theory/data/selfopen01_t3.json: the T3 file's sha256, the self-open test, the problem indices whose stored T3
row passes it (kept unchanged) and the others (regenerated by jobs/selfopen_gen.py). Standard library only.
"""
import hashlib
import json
import pathlib
import sys

T3_URI = "s3://pg-lineage-769063704696/results/rlneurons/r4/modal_t3-01/t3/T3.jsonl"
OUT = pathlib.Path(__file__).resolve().parents[1] / "data" / "selfopen01_t3.json"


def self_opens(text: str) -> bool:
    """The test of the r5-m10 entry: a newline followed by 'Okay' inside the first 60 characters of the answer text."""
    return "\nOkay" in text[:60]


def main():
    p = pathlib.Path(sys.argv[1])
    rows = [json.loads(l) for l in p.open() if l.strip()]
    assert sorted(r["problem_index"] for r in rows) == list(range(500)), "T3 is not one row per MATH-500 problem"
    assert all(r["prefix_kind"] == "none" and r["seed"] == 47_000_000 + r["problem_index"] for r in rows), "not the plain T3 cell"
    assert self_opens(".\n\nOkay, so") and not self_opens(" Okay, so") and not self_opens("x" * 56 + "\nOkay"), "self-open test"
    so = sorted(r["problem_index"] for r in rows if self_opens(r["text"]))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps({"source": T3_URI, "sha256": hashlib.sha256(p.read_bytes()).hexdigest(),
                               "test": "'\\nOkay' in text[:60]", "n_self_opened": len(so), "self_opened": so,
                               "regenerate": [i for i in range(500) if i not in set(so)]}, indent=1))
    print(OUT, len(so), "self-opened of 500")


if __name__ == "__main__":
    main()
